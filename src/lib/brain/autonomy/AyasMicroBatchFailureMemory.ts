import crypto from "node:crypto";
import path from "node:path";

import { AyasValidatorFailedError } from "./AyasMutationValidators";
import type { AyasBoundedFileReplacement } from "./AyasBoundedFileWrite";
import { createAyasSandboxUnvalidatableStore, type AyasSandboxUnvalidatableRecord, type AyasSandboxUnvalidatableStore } from "./AyasSandboxUnvalidatableStore";

/**
 * Micro-batch lane memory of candidates that failed sandbox validation (owner decision 2026-11-19, approving the
 * 14 Nov follow-up "mikro-parti başarısız adayı HEAD başına hatırlama"). On 14 Nov the observer re-validated
 * `ayas-novel-v3-budget` every 5 minutes and failed it 293 times: `AyasMicroBatchAccumulator` remembered nothing about a
 * failed candidate, so the same doomed typecheck + smoke ran on every tick at an unchanged HEAD. The individual-proposal
 * lane (`AyasNovelPatchDiscovery`) already had this memory; the micro lane did not.
 *
 * A failure is remembered for the exact validation it ran: HEAD, the batch items already applied in the worktree it
 * was validated in, and the candidate's own generated bytes (`ayasMicroCandidateValidationFingerprint`). A changed HEAD,
 * batch or candidate is a different fingerprint and is tried again on its own. A real validation failure is not
 * repeated on the same fingerprint; a failure that looks like the environment (a timeout, a killed process, a missing
 * local binary, a write that never reached the validators) is tried up to `AYAS_MICRO_BATCH_TRANSIENT_ATTEMPTS` times in
 * total on the same fingerprint and then held until the fingerprint changes. This only ever skips the sandbox attempt;
 * it never adds, approves, publishes or authorizes anything.
 *
 * Records reuse the individual lane's store format, in their own subdirectory (`sandbox-unvalidatable/micro-batch/`,
 * already covered by `.gitignore`; that store's own listing reads `.json` files only, so the two never mix).
 */
export const AYAS_MICRO_BATCH_TRANSIENT_ATTEMPTS = 3;

export type AyasMicroValidationFailureKind = "VALIDATION_FAILED" | "TRANSIENT";

/** The environment, not the candidate: timeouts, killed or missing processes, resource exhaustion, a suite that skipped itself. */
const TRANSIENT_FAILURE = /\bETIMEDOUT\b|timed out|\bSIG(?:TERM|KILL)\b|\bE(?:NOMEM|BUSY|MFILE|NFILE|NOSPC|AGAIN|PERM|ACCES)\b|maxBuffer|is unavailable|validator target script does not exist|validator threw|malformed result|skipped itself/i;

/**
 * Decides whether a failed micro-batch validation was the candidate (`VALIDATION_FAILED`) or the environment
 * (`TRANSIENT`). Anything that is not a validator verdict (the bounded write, its rollback, the worktree) is transient; a
 * validator verdict is transient only when its failing summary names an environment cause. A wrong guess costs at most
 * `AYAS_MICRO_BATCH_TRANSIENT_ATTEMPTS` attempts per fingerprint, never a skipped HEAD.
 */
export function classifyAyasMicroValidationFailure(error: unknown): AyasMicroValidationFailureKind {
  if (!(error instanceof AyasValidatorFailedError)) return "TRANSIENT";
  const failing = error.results.find((result) => !result.pass);
  if (!failing) return "TRANSIENT";
  return TRANSIENT_FAILURE.test(failing.summary) ? "TRANSIENT" : "VALIDATION_FAILED";
}

/**
 * Identity of one validation: HEAD, the patch hashes already applied in the batch worktree (order-free), and every
 * generated file path with its bytes. Owner 2026-11-19: "aynı HEAD + aynı aday hash'i" — and the batch the candidate was
 * validated against, since a candidate can fail only because of an item already in the worktree.
 */
export function ayasMicroCandidateValidationFingerprint(input: { readonly head: string; readonly batchPatchHashes: readonly string[]; readonly generatorIdentity: string; readonly replacements: readonly Pick<AyasBoundedFileReplacement, "filePath" | "content">[] }): string {
  const files = input.replacements
    .map((r) => ({ filePath: r.filePath, sha256: crypto.createHash("sha256").update(r.content, "utf8").digest("hex") }))
    .sort((a, b) => (a.filePath < b.filePath ? -1 : a.filePath > b.filePath ? 1 : 0));
  const identity = { v: 1, head: input.head, batch: [...input.batchPatchHashes].sort(), generator: input.generatorIdentity, files };
  return crypto.createHash("sha256").update(JSON.stringify(identity), "utf8").digest("hex");
}

/**
 * `true` when this exact validation already failed and must not run again: a real failure at once, a transient one
 * after `AYAS_MICRO_BATCH_TRANSIENT_ATTEMPTS` attempts. An absent or other-fingerprint record never suppresses.
 */
export function isAyasMicroCandidateSuppressed(record: AyasSandboxUnvalidatableRecord | undefined, fingerprint: string): boolean {
  if (record === undefined || record.contentFingerprint !== fingerprint) return false;
  if (record.retryable !== true) return true;
  return !(record.attemptCount < AYAS_MICRO_BATCH_TRANSIENT_ATTEMPTS);
}

/** The micro lane's own record directory under the repository's runtime data (ignored by Git). */
export function createAyasMicroBatchFailureStore(repoRoot: string): AyasSandboxUnvalidatableStore {
  return createAyasSandboxUnvalidatableStore({ rootDir: path.join(repoRoot, "data", "brain", "self-improvement", "sandbox-unvalidatable", "micro-batch") });
}
