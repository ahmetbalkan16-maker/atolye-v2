import assert from "node:assert/strict";
import fs from "node:fs";
import path from "node:path";
import os from "node:os";
import { createRuntimeStorageContext } from "../src/lib/runtime/RuntimeStoragePaths";
import { writeRuntimeAuthorityGenerationMarker } from "../src/lib/runtime/security/RuntimeAuthorityGenerationMarker";
import { RuntimeAuthorityTransitionStore } from "../src/lib/runtime/security/RuntimeAuthorityTransition";
import { beginTransition, confirmQuiescence, prepareTransition, validateTarget, publishTransition, quarantineSource } from "../src/lib/runtime/security/RuntimeAuthorityTransitionCoordinator";
import { finalizeOldRootQuarantine, beginTokenAuthorizedRollback, validateRollback, publishRollback, quarantineFormerTarget } from "../src/lib/runtime/security/RuntimeAuthorityRollback";
import { enforceProductionRuntimeAuthorityGeneration } from "../src/lib/runtime/security/ProductionRuntimeAuthorityGenerationEnforcement";
const root=fs.mkdtempSync(path.join(os.tmpdir(),"ayas-authority-workspace-"));
const oldWorkspace=path.join(root,"old-workspace"),newWorkspace=path.join(root,"new-workspace"),oldRuntime=path.join(root,"old-runtime"),newRuntime=path.join(root,"new-runtime"),oldAuthority=path.join(root,"old-authority"),newAuthority=path.join(root,"new-authority");
for(const dir of [oldWorkspace,newWorkspace,oldAuthority,newAuthority,path.join(oldRuntime,"projects/test-project"),path.join(newRuntime,"projects")])fs.mkdirSync(dir,{recursive:true});
fs.writeFileSync(path.join(oldRuntime,"projects/test-project/project.json"),JSON.stringify({id:"00000000-0000-4000-8000-000000000001",slug:"test-project"}));
const source=createRuntimeStorageContext({workspaceRoot:oldWorkspace,authorityRoot:oldAuthority,environment:{ATOLYE_RUNTIME_ROOT:oldRuntime}});
const target=createRuntimeStorageContext({workspaceRoot:newWorkspace,authorityRoot:newAuthority,environment:{ATOLYE_RUNTIME_ROOT:newRuntime}});
const generation="runtime-authority-generation-v1",transitionId="fixture-workspace-handoff";
writeRuntimeAuthorityGenerationMarker({context:source,authorityGeneration:generation});
const store=new RuntimeAuthorityTransitionStore({authorityRoot:oldAuthority});
beginTransition({store,transitionId,sourceContext:source,sourceAuthorityGeneration:generation,targetContext:target,targetAuthorityGeneration:generation});
assert.throws(()=>enforceProductionRuntimeAuthorityGeneration(source,generation,{env:{NODE_ENV:"production"}}));
confirmQuiescence({store,transitionId,workerLifecycleState:"stopped",durableRecovery:"clean"});
const projectId="00000000-0000-4000-8000-000000000001";
prepareTransition({store,transitionId,sourceProjectSlugs:["test-project"],sourceProjectsRoot:source.projectsRoot, projectIdentities:[{projectId,projectSlug:"test-project"}]});
fs.cpSync(path.join(source.projectsRoot,"test-project"),path.join(target.projectsRoot,projectId),{recursive:true});
const validated=validateTarget({store,transitionId,targetContext:target,targetAuthorityGeneration:generation,targetProjectSlugs:[projectId],targetProjectsRoot:target.projectsRoot});
assert(validated.targetValidation?.byteExact);
publishTransition({store,transitionId,targetContext:target,targetAuthorityGeneration:generation});
quarantineSource({store,transitionId});
const finalized=finalizeOldRootQuarantine({store,transitionId,oldRootProjectsRoot:source.projectsRoot});
assert(finalized.rollbackToken);
// Offline handoff copies official state only after all old writers stopped.
fs.cpSync(oldAuthority,newAuthority,{recursive:true});
assert.equal(enforceProductionRuntimeAuthorityGeneration(target,generation,{env:{NODE_ENV:"production"}}).mode,"match");
assert.throws(()=>enforceProductionRuntimeAuthorityGeneration(source,generation,{env:{NODE_ENV:"production"}}));
const relocated=new RuntimeAuthorityTransitionStore({authorityRoot:newAuthority});
assert.deepEqual(relocated.readActiveAuthority(),store.readActiveAuthority());
assert.equal(relocated.readTransition(transitionId)?.state,"old-root-quarantined");
console.log("PASS workspace/runtime/authority-root change: official byte-exact publish, offline store handoff, new root allowed and old root denied");

const token=finalized.rollbackToken!;
const rollbackTransitionId="fixture-workspace-rollback";
const common={store:relocated,rollbackTransitionId,oldRootProjectsRoot:source.projectsRoot,formerTargetProjectsRoot:target.projectsRoot};
fs.writeFileSync(path.join(target.projectsRoot,projectId,"drift.txt"),"changed");
assert.throws(()=>beginTokenAuthorizedRollback({...common,tokenId:token.tokenId,oldRootContext:source,oldRootAuthorityGeneration:generation,formerTargetContext:target,formerTargetAuthorityGeneration:generation}));
fs.unlinkSync(path.join(target.projectsRoot,projectId,"drift.txt"));
beginTokenAuthorizedRollback({...common,tokenId:token.tokenId,oldRootContext:source,oldRootAuthorityGeneration:generation,formerTargetContext:target,formerTargetAuthorityGeneration:generation});
validateRollback(common);
publishRollback(common);
quarantineFormerTarget(common);
fs.cpSync(newAuthority,oldAuthority,{recursive:true});
assert.equal(enforceProductionRuntimeAuthorityGeneration(source,generation,{env:{NODE_ENV:"production"}}).mode,"match");
assert.throws(()=>enforceProductionRuntimeAuthorityGeneration(target,generation,{env:{NODE_ENV:"production"}}));
assert(relocated.readRollbackTokenConsumption(token.tokenId));
console.log("PASS identity-mapped workspace rollback: untouched data required, official token consumed, offline return, old allowed / new denied");
