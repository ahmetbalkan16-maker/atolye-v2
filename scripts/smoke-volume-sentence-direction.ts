assert.equal(narrationSentenceAction('The website explains conditions.'),'TALK');
assert.equal(narrationSentenceAction('Asker koşuyor.'),'RUN');
assert.equal(narrationSentenceAction('Şimdi oturuyoruz.'),'SIT');
assert.equal(narrationCameraZoom(2.4,track),1,'silence gap stays wide');
assert(narrationCameraZoom(1,track)>1);
assert.equal(narrationCameraZoom(3.3,track),1,'bow stays wide');
