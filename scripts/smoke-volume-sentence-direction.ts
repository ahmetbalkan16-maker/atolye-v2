const frames=[.5,1,1.5,2,3.9,4.1,5.5,7.9].map(t=>{const d=volumeNarratedActor(lead,blocking,planned.animation,move,t,138);return volumePerformanceFrame(d.character,d.actor,d.frame,d.clock,138,true);});
